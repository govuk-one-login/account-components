import { AppConfigProvider } from "@aws-lambda-powertools/parameters/appconfig";
import { getEnvironment } from "../getEnvironment/index.js";
import { getAppConfigClient } from "../awsClient/appconfigClient/index.js";
import type { AppConfigSchema } from "../../../config/schema/types.js";

let provider: AppConfigProvider | undefined;

export async function getAppConfig(): Promise<AppConfigSchema> {
  provider ??= new AppConfigProvider({
    application: "account-components",
    environment: getEnvironment(),
    awsSdkV3Client: getAppConfigClient().client,
  });

  const config = await provider.get("operational", {
    transform: "json",
    maxAge: 300,
  });

  // Type assertion is okay as the config is validated at deploy time
  // against the JSON schema from which the AppConfigSchema type is
  // autogenerated
  // eslint-disable-next-line @typescript-eslint/consistent-type-assertions
  return config as unknown as AppConfigSchema;
}
